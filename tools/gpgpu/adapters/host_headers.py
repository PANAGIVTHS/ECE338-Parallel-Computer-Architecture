"""The host driver's two generated C headers. Both are committed, so its build needs neither."""
from __future__ import annotations

import re
import subprocess
from functools import partial
from pathlib import Path
from typing import Annotated, Any

from pydantic import Field, NonNegativeInt, PositiveInt, StringConstraints

from gpgpu.api import Step

from .config import Config, Section
from .design import architecture, program_names, program_output, rtl_root, rtl_sources

CName = Annotated[str, StringConstraints(pattern=r"^[A-Za-z_][A-Za-z0-9_]*$")]
Header = Annotated[str, StringConstraints(pattern=r".*\.h$")]
Word = Annotated[int, Field(ge=0, le=0xFFFFFFFF)]

# Linker symbols bounding GPGPU_ARGS (gpgpu.ld): the host writes the arguments there.
_ARGS_BASE, _ARGS_END = "__gpu_args_base", "__gpu_args_end"


class _Autorun(Section):
    header: Header
    enabled: bool
    program: str
    args: list[Word | CName]
    display: NonNegativeInt


class _Host(Section):
    platform_header: Header
    export_attribute: CName
    define_prefix: CName
    use_irq: bool
    irq_id: PositiveInt
    autorun: _Autorun


def _guard(header: Path) -> str:
    return re.sub(r"\W", "_", header.name).upper()


def _c_value(value: int | tuple[int, ...] | tuple[str, ...], hex_digits: int | None) -> str:
    """A C literal for an exported value; a tuple is an initializer list."""
    if isinstance(value, tuple):
        return "{ " + ", ".join(f'"{item}"' if isinstance(item, str) else _c_value(item, hex_digits) for item in value) + " }"
    return f"{value}U" if hex_digits is None else f"0x{value:0{hex_digits}X}U"


def _write_platform(sources: list[Path], include_directory: Path, settings: dict[str, Any], output: Path) -> None:
    from .slang import read_exports  # loaded only when a header is really generated

    def define(name: str, value: str) -> None:
        lines.append(f"#define {settings['define_prefix']}{name:<28} {value}")

    guard = _guard(output)
    lines = ["/* Generated by `gpgpu software host:platform`",
             f" * from the (* {settings['export_attribute']} *) declarations in the RTL and the configuration.",
             " * Do not edit: change the RTL or the configuration and regenerate.",
             " */", f"#ifndef {guard}", f"#define {guard}", "",
             "/* Interface version reported in INFO[31:16] (architecture.interface_version). */"]
    define("INTERFACE_VERSION", f"{settings['interface_version']}U")
    package = None
    for export in read_exports(sources, include_directory, settings["export_attribute"]):
        if export.package != package:
            package = export.package
            lines += ["", f"/* {package} */"]
        define(export.name, _c_value(export.value, export.hex_digits))
    lines += ["", "/* Completion wait: PS interrupt or IRQ_STATUS polling (software.host). */"]
    define("USE_IRQ", "1" if settings["use_irq"] else "0")
    define("IRQ_ID", f"{settings['irq_id']}U")
    lines += ["", f"#endif /* {guard} */", ""]
    output.write_text("\n".join(lines), encoding="utf-8")


def platform_step(config: Config) -> Step:
    host = config.section("software.host", _Host)
    sources, headers = rtl_sources(config, list(config.get("hardware.vivado.exclude_sources")))
    settings = {"export_attribute": host.export_attribute, "define_prefix": host.define_prefix,
                "interface_version": architecture(config).interface_version, "use_irq": host.use_irq, "irq_id": host.irq_id}
    output = config.repo_root / host.platform_header
    return Step(partial(_write_platform, sources, rtl_root(config), settings, output),
                inputs=(*sources, *headers, Path(__file__)), outputs=(output,), fingerprint=settings)


def _args_window(nm_command: list[str]) -> tuple[int, int]:
    """(first DMEM word, word count) of GPGPU_ARGS, from the program's symbols."""
    listing = subprocess.run(nm_command, check=True, capture_output=True, text=True).stdout
    symbols = {fields[2]: int(fields[0], 16) for fields in map(str.split, listing.splitlines())
               if len(fields) == 3 and fields[2] in (_ARGS_BASE, _ARGS_END)}
    if len(symbols) != 2:
        raise ValueError(f"{' '.join(nm_command)}: no symbols {_ARGS_BASE} and {_ARGS_END}")
    base, end = symbols[_ARGS_BASE], symbols[_ARGS_END]
    if base % 4 or end % 4 or end <= base:
        raise ValueError(f"GPGPU_ARGS window 0x{base:x}..0x{end:x} is not whole words")
    return base // 4, (end - base) // 4


def _write_autorun(settings: dict[str, Any], nm_command: list[str] | None, memory: Path | None, output: Path) -> None:
    def define(name: str, value: str) -> None:
        lines.append(f"#define {settings['define_prefix']}{name:<28} {value}")

    guard = _guard(output)
    lines = ["/* Generated by `gpgpu software host:autorun`",
             " * from software.host.autorun and the program's RISC-V build.",
             " * Do not edit: change the configuration and regenerate.",
             " */", f"#ifndef {guard}", f"#define {guard}", "",
             "/* Program run from boot until a UART key press (software.host.autorun). */"]
    if nm_command is None or memory is None:
        define("AUTORUN", "0")
    else:
        image = [int(line, 16) for line in memory.read_text(encoding="utf-8").split()]
        args_word, args_words = _args_window(nm_command)
        args = settings["args"]
        if len(args) > args_words:
            raise ValueError(f"software.host.autorun.args has {len(args)} values; GPGPU_ARGS holds {args_words} words")
        values = [f"0x{arg:08X}U" if isinstance(arg, int) else arg for arg in args]
        values += ["0x00000000U"] * (args_words - len(values))
        define("AUTORUN", "1")
        define("AUTORUN_PROGRAM", f"\"{settings['program']}\"")
        lines.append("/* First DMEM word of GPGPU_ARGS (__gpu_args_base in gpgpu.ld). */")
        define("AUTORUN_ARGS_WORD", f"{args_word}U")
        lines.append("/* Framebuffer shown while it runs (software.host.autorun.display). */")
        define("AUTORUN_DISPLAY", f"{settings['display']}U")
        lines += ["", "/* IMEM image, from word 0. */", "static const u32 gpgpu_autorun_image[] = {"]
        lines += [f"    {', '.join(f'0x{word:08X}U' for word in image[i:i + 6])}," for i in range(0, len(image), 6)]
        lines += ["};", "", "/* GPGPU_ARGS words (software.host.autorun.args; the rest are 0). */",
                  f"static const u32 gpgpu_autorun_args[] = {{ {', '.join(values)} }};"]
    lines += ["", f"#endif /* {guard} */", ""]
    output.write_text("\n".join(lines), encoding="utf-8")


def autorun_program(config: Config) -> str | None:
    autorun = config.section("software.host", _Host).autorun
    return autorun.program if autorun.enabled else None


def autorun_step(config: Config, nm: str) -> Step:
    host = config.section("software.host", _Host)
    autorun = host.autorun
    if autorun.enabled and autorun.program not in program_names(config):
        raise ValueError(f"software.host.autorun.program must be one of: {', '.join(program_names(config))}")
    settings = {**autorun.model_dump(), "define_prefix": host.define_prefix}
    output = config.repo_root / autorun.header
    this = Path(__file__)
    if not autorun.enabled:
        return Step(partial(_write_autorun, settings, None, None, output), inputs=(this,), outputs=(output,), fingerprint=settings)
    elf = program_output(config, autorun.program, ".elf")
    memory = program_output(config, autorun.program, "_instructions.mem")
    return Step(partial(_write_autorun, settings, [nm, str(elf)], memory, output),
                inputs=(elf, memory, this), outputs=(output,), fingerprint=settings)
