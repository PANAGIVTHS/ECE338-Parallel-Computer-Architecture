"""The black boxes. Adapters implement these; only bootstrap.py knows which one does."""
from __future__ import annotations

from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any, ContextManager, Protocol, TypeVar

from .model import CheckResult, Step, SyncReport, SyncState, Task

T = TypeVar("T")


class Backends(Protocol):
    """How a plugin gets the black box for its category: `flow = backend(HardwareFlow)`."""

    def __call__(self, port: type[T]) -> T: ...


# What the application needs.

class TaskEngine(Protocol):
    def run(self, tasks: Sequence[Task], target: str, *, monitor: bool) -> int:
        """Run target among exactly these tasks, skipping what is fresh. 0 ok, 1 task failed, 2 engine error."""
        ...

    def stale(self, tasks: Sequence[Task]) -> list[str]:
        """Why these tasks would rerun; empty when their results are current."""
        ...


class Settings(Protocol):
    """Read-only resolved configuration, for `gpgpu config`."""

    profile: str

    @property
    def build_root(self) -> Path: ...
    def get(self, key: str, default: Any = ...) -> Any: ...
    def source_of(self, key: str) -> str: ...
    def as_dict(self) -> dict[str, Any]: ...
    def keys(self) -> list[str]: ...
    def unknown_keys(self) -> list[str]: ...


class Environment(Protocol):
    def checks(self) -> list[CheckResult]:
        """What `gpgpu doctor` reports about this machine."""
        ...

    def exclusive(self, categories: Iterable[str], command: str) -> ContextManager[None]:
        """Hold these categories for one command. Raises GpgpuError if another command holds one."""
        ...


class DesignProject(Protocol):
    """A design that scripts generate and a GUI can edit."""

    name: str
    create_task: str                 # the task that builds the project
    blocked_by: frozenset[SyncState]  # states in which a build would lose or ignore edits

    def status(self) -> SyncReport: ...
    def pull(self, *, force: bool = False) -> SyncReport: ...  # project -> committed files
    def push(self, *, force: bool = False) -> SyncReport: ...  # committed files -> project
    def open(self) -> None: ...


# What each plugin needs. Every method describes one step; running it is the engine's job.

class HardwareFlow(Protocol):
    """RTL -> packaged IP -> system project -> bitstream -> hardware platform."""

    def identity(self) -> Step: ...
    def create_ip(self) -> Step: ...
    def package_ip(self) -> Step: ...
    def create_system(self) -> Step: ...
    def synthesize(self) -> Step: ...
    def implement(self) -> Step: ...
    def bitstream(self) -> Step: ...
    def export_hardware(self) -> Step: ...
    def projects(self) -> list[DesignProject]: ...


class PlatformFlow(Protocol):
    """Hardware platform -> software platform -> host application."""

    def create_project(self) -> Step: ...
    def build_platform(self) -> Step: ...
    def build_host(self) -> Step: ...
    def export_project(self) -> Step: ...


class RtlFlow(Protocol):
    """Build identity, expected results, and simulation of the RTL."""

    def identity(self) -> Step: ...
    def constants(self) -> Step: ...
    def generate(self) -> Step: ...
    def build_suite(self, suite: str) -> Step: ...
    def run_suite(self, suite: str) -> Step: ...
    def random(self) -> Step: ...


class Toolchain(Protocol):
    """Program builds, native and for the GPGPU, and the host driver's generated headers."""

    def programs(self) -> list[str]: ...
    def clean(self, program: str) -> Step: ...
    def build_native(self, program: str) -> Step: ...
    def run_native(self, program: str) -> Step: ...
    def build_elf(self, program: str) -> Step: ...
    def disassemble(self, program: str) -> Step: ...
    def assembly(self, program: str) -> Step: ...
    def memory_image(self, program: str) -> Step: ...
    def host_platform_header(self) -> Step: ...
    def host_autorun_header(self) -> Step: ...
    def autorun_program(self) -> str | None: ...


class Board(Protocol):
    """The programmable target. Its steps always run: they act on the outside world."""

    def programs(self) -> list[str]: ...
    def upload(self) -> Step: ...
    def preflight(self) -> Step: ...
    def reset(self) -> Step: ...
    def set_mode(self, mode: str) -> Step: ...
    def program(self) -> Step: ...
    def upload_program(self, program: str) -> Step: ...
    def load_program(self, program: str) -> Step: ...
    def run_program(self, program: str) -> Step: ...
